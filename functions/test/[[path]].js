export function onRequest({ request, next }) {
  const pathname = new URL(request.url).pathname;
  const rest = pathname.startsWith('/test/') ? pathname.slice('/test/'.length) : '';
  // Accept exactly a PDF detail URL, with an optional trailing slash or index.html.
  const match = /^([^/]+)(?:\/(?:index\.html)?)?$/.exec(rest);
  let filename = '';
  if (match) {
    try { filename = decodeURIComponent(match[1]); } catch { /* reject malformed escapes */ }
  }
  if (ALLOWED_PDFS.has(filename)) return next();
  return new Response(request.method === 'HEAD' ? null : notFoundHtml, {
    status: 404,
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
      'X-Robots-Tag': 'noindex, nofollow',
      'Cache-Control': 'no-store',
    },
  });
}
